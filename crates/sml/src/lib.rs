/// A state machine generated by [`sml!`].
///
/// Drive it with [`Sm`]; the methods here are the protocol used between parent
/// and composite machines.
pub trait StateMachine: Sized {
    /// Data shared by guards and actions (and with composite sub-machines).
    type Context;
    /// Generated enum of this machine's states.
    type State: Copy + Eq + Debug;

    /// Machine positioned at its initial state, before entry actions run.
    fn initial() -> Self;
    /// Currently active state.
    fn state(&self) -> Self::State;
    /// Enters the machine: resets to the initial state (unless it has history),
    /// then runs entry actions and anonymous transitions.
    fn enter(&mut self, ctx: &mut Self::Context);
    /// Exits the active state, running exit actions innermost first.
    fn exit(&mut self, ctx: &mut Self::Context);
    /// Dispatches `event`; returns whether a row fired.
    fn handle<E: Any>(&mut self, ctx: &mut Self::Context, event: &E) -> bool;
    /// Whether the machine reached `X`.
    fn is_terminated(&self) -> bool;
}

/// Access to the sub-machine behind composite state `state<S>`.
pub trait SubMachine<S> {
    /// The sub-machine instance (keeps its state while inactive, for history).
    fn sub(&self) -> &S;
}

/// Runs a [`StateMachine`] and owns its context, like `boost::sml::sm<T>`.
#[derive(Debug)]
pub struct Sm<M: StateMachine> {
    machine: M,
    ctx: M::Context,
}

impl<M: StateMachine> Sm<M> {
    /// Starts the machine: enters the initial state and runs anonymous transitions.
    pub fn new(mut ctx: M::Context) -> Self {
        let mut machine = M::initial();
        machine.enter(&mut ctx);
        Self { machine, ctx }
    }

    /// Dispatches `event`; returns `true` if a transition (or internal action) fired.
    pub fn process_event<E: Any>(&mut self, event: E) -> bool {
        let handled = self.machine.handle(&mut self.ctx, &event);
        __private::log_process_event::<M, E>(handled);
        handled
    }

    /// Currently active top-level state.
    pub fn state(&self) -> M::State {
        self.machine.state()
    }

    /// Whether `state` is the active top-level state.
    pub fn is(&self, state: M::State) -> bool {
        self.machine.state() == state
    }

    /// Whether the machine reached the terminate state `X`.
    pub fn is_terminated(&self) -> bool {
        self.machine.is_terminated()
    }

    /// Composite sub-machine `S`, e.g. `sm.sub::<Inner>().state()`.
    pub fn sub<S>(&self) -> &S
    where
        M: SubMachine<S>,
    {
        self.machine.sub()
    }

    /// Shared context.
    pub fn context(&self) -> &M::Context {
        &self.ctx
    }

    /// Mutable shared context.
    pub fn context_mut(&mut self) -> &mut M::Context {
        &mut self.ctx
    }

    /// Consumes the machine, returning its context.
    pub fn into_context(self) -> M::Context {
        self.ctx
    }
}

/// Support code for [`sml!`] expansions. Not public API.
#[doc(hidden)]
pub mod __private {
    pub use crate::log::{log_action, log_guard, log_process_event, log_state_change};

    /// Marker: callable takes the event.
    pub struct WithEvent;
    /// Marker: callable ignores the event.
    pub struct NoEvent;

    /// Guard callable, with or without the event parameter.
    #[diagnostic::on_unimplemented(
        message = "`{Self}` is not a valid guard",
        label = "invalid guard",
        note = "guards are `Fn(&Context, &Event) -> bool` or `Fn(&Context) -> bool`",
        note = "closures need explicit parameter types: `|ctx: &Ctx| ...`"
    )]
    pub trait Guard<C, E: ?Sized, M> {
        /// Evaluates the guard.
        fn check(&self, ctx: &C, event: &E) -> bool;
    }

    impl<C, E: ?Sized, F: Fn(&C, &E) -> bool> Guard<C, E, WithEvent> for F {
        fn check(&self, ctx: &C, event: &E) -> bool {
            self(ctx, event)
        }
    }

    impl<C, E: ?Sized, F: Fn(&C) -> bool> Guard<C, E, NoEvent> for F {
        fn check(&self, ctx: &C, _event: &E) -> bool {
            self(ctx)
        }
    }

    /// Action callable, with or without the event parameter.
    #[diagnostic::on_unimplemented(
        message = "`{Self}` is not a valid action",
        label = "invalid action",
        note = "actions are `Fn(&mut Context, &Event)` or `Fn(&mut Context)`",
        note = "closures need explicit parameter types: `|ctx: &mut Ctx| ...`"
    )]
    pub trait Action<C, E: ?Sized, M> {
        /// Runs the action.
        fn call(&self, ctx: &mut C, event: &E);
    }

    impl<C, E: ?Sized, F: Fn(&mut C, &E)> Action<C, E, WithEvent> for F {
        fn call(&self, ctx: &mut C, event: &E) {
            self(ctx, event);
        }
    }

    impl<C, E: ?Sized, F: Fn(&mut C)> Action<C, E, NoEvent> for F {
        fn call(&self, ctx: &mut C, _event: &E) {
            self(ctx);
        }
    }
}

