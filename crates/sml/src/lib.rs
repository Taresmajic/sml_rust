//! Finite state machines with a transition-table DSL modelled on
//! [Boost.SML](https://github.com/boost-ext/sml).
//!
//! ```
//! use sml::{sml, Sm};
//!
//! #[derive(Default)]
//! struct Ctx { opened: u32, locked: bool }
//!
//! struct Open;
//! struct Close;
//! struct Kick;
//!
//! fn is_unlocked(ctx: &Ctx) -> bool { !ctx.locked }
//! fn count(ctx: &mut Ctx, _: &Open) { ctx.opened += 1; }
//!
//! sml! {
//!     machine Door<Ctx>;
//!     *Closed + Open [is_unlocked] / count = Opened,
//!      Opened + Close                      = Closed,
//!      Opened + Kick                       = X,
//! }
//!
//! let mut sm = Sm::<Door>::new(Ctx::default());
//! assert!(sm.is(DoorState::Closed));
//! assert!(sm.process_event(Open));
//! assert!(sm.is(DoorState::Opened));
//! assert!(!sm.process_event(Open));
//! sm.process_event(Kick);
//! assert!(sm.is_terminated());
//! assert_eq!(sm.context().opened, 1);
//! ```
//!
//! # Table syntax
//!
//! ```text
//! [pub] machine Name[<Context>];
//! [*]src[(H)] [+ trigger] [[guard]] [/ action] [= dst],
//! ```
//!
//! | element       | forms                                                          |
//! |---------------|----------------------------------------------------------------|
//! | state         | `Ident`, `state<SubMachine>` (composite), `X` (terminate); `state` is reserved |
//! | `*`           | marks the initial state                                        |
//! | `(H)`         | on the initial state: re-entering resumes the last active state|
//! | trigger       | event type, `on_entry`, `on_exit`, `unexpected_event[<T\|_>]`  |
//! | guard         | paths/closures combined with `&&`, `\|\|`, `!` and parentheses  |
//! | action        | a path, or `(a, b, \|ctx: &mut C\| ...)` run in order           |
//! | no trigger    | anonymous transition, taken as soon as its guard holds         |
//! | no `= dst`    | internal transition: action runs, no exit/entry                |
//!
//! Guards are `Fn(&Context, &Event) -> bool` or `Fn(&Context) -> bool`; actions are
//! `Fn(&mut Context, &Event)` or `Fn(&mut Context)`. Entry, exit and anonymous
//! transitions have no event (`&()`); `unexpected_event<_>` passes `&dyn Any`.
//! Closures need explicit parameter types.
//!
//! # Semantics
//!
//! - Rows are tried in declaration order; the first whose guard holds fires.
//! - External transition: exit src (inner machines first), action, enter dst
//!   (outer first), then anonymous transitions of dst.
//! - A composite state forwards events to its sub-machine first; the parent's rows
//!   apply only when the sub-machine does not handle the event.
//! - `unexpected_event` rows fire only when no other row of the state names the
//!   event type.
//! - Once in `X`, every event is ignored.
//!
//! # Diagrams
//!
//! With the `diagram` feature, each machine's rustdoc shows its state diagram and the
//! machine implements `Diagram` (`graph()`, `diagram_svg()`); the layout engine is
//! the `sml-diagram` crate, re-exported as `sml::diagram`.
//!
//! # Logging
//!
//! With the `tracing` feature, machines emit [`tracing`](https://docs.rs/tracing) events
//! (target `sml`), mirroring Boost.SML's logger policy: processed events and state
//! changes at `DEBUG`, guard results and actions at `TRACE`. Without the feature the
//! hooks compile to nothing.

