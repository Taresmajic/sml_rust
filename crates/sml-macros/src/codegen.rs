//! Expansion of a validated [`Model`] into a `StateMachine` implementation.

use proc_macro2::TokenStream;
use quote::{format_ident, quote, quote_spanned};
use syn::spanned::Spanned;
use syn::{Expr, Ident};

use crate::ast::GuardExpr;
use crate::model::{Model, State, StateKind, Transition, TransitionTrigger, to_snake_case};

/// Expansion of `model`; `docs` are appended to the machine struct's documentation.
pub fn generate(model: &Model, docs: &[String]) -> TokenStream {
    let generator = Gen { model, docs };
    let types = generator.types();
    let machine = generator.state_machine_impl();
    let subs = generator.sub_machine_impls();
    let helpers = generator.helpers();
    quote! { #types #machine #subs #helpers }
}

fn is_anonymous(trigger: &TransitionTrigger) -> bool {
    match trigger {
        TransitionTrigger::Anonymous => true,
        TransitionTrigger::Event(_) | TransitionTrigger::Unexpected(_) => false,
    }
}

fn is_unexpected(trigger: &TransitionTrigger) -> bool {
    match trigger {
        TransitionTrigger::Unexpected(_) => true,
        TransitionTrigger::Anonymous | TransitionTrigger::Event(_) => false,
    }
}

struct Gen<'a> {
    model: &'a Model,
    docs: &'a [String],
}

impl Gen<'_> {
    fn types(&self) -> TokenStream {
        let Model {
            vis,
            name,
            state_enum,
            ..
        } = self.model;
        let variants = self.model.states.iter().map(|s| {
            let name = &s.name;
            let doc = format!("State `{name}`.");
            quote! { #[doc = #doc] #name }
        });
        let fields = self.sub_fields().map(|(field, ty)| quote! { #field: #ty, });
        let doc = format!("States of [`{name}`].");
        let machine_doc = format!("State machine `{name}`, generated by `sml!`.");
        let docs = self.docs;
        quote! {
            #[doc = #doc]
            #[derive(Clone, Copy, PartialEq, Eq, Debug)]
            #vis enum #state_enum { #(#variants,)* }

            #[doc = #machine_doc]
            #(#[doc = #docs])*
            #[derive(Debug)]
            #vis struct #name {
                state: #state_enum,
                #(#fields)*
            }
        }
    }

    fn sub_fields(&self) -> impl Iterator<Item = (Ident, &syn::Type)> {
        self.model
            .states
            .iter()
            .filter_map(|s| s.composite().map(|ty| (Model::sub_field(s), ty)))
    }

    fn state_machine_impl(&self) -> TokenStream {
        let Model {
            name,
            state_enum,
            context,
            ..
        } = self.model;
        let initial = &self.model.states[self.model.initial].name;
        let sub_inits = self.sub_fields().map(|(field, ty)| {
            quote! { #field: <#ty as ::sml::StateMachine>::initial(), }
        });
        let reset = if self.model.history {
            quote! {}
        } else {
            quote! { self.state = #state_enum::#initial; }
        };
        let handle = self.handle_fn();
        let terminate = self.model.states.iter().find(|s| is_terminate(s));
        let terminated = terminate.map_or_else(
            || quote! { false },
            |x| {
                let x = &x.name;
                quote! { self.state == #state_enum::#x }
            },
        );
        quote! {
            impl ::sml::StateMachine for #name {
                type Context = #context;
                type State = #state_enum;

                fn initial() -> Self {
                    Self { state: #state_enum::#initial, #(#sub_inits)* }
                }

                fn state(&self) -> #state_enum {
                    self.state
                }

                fn enter(&mut self, ctx: &mut #context) {
                    #reset
                    self.__sml_enter_state(ctx);
                }

                fn exit(&mut self, ctx: &mut #context) {
                    self.__sml_exit_state(ctx);
                }

                #handle

                fn is_terminated(&self) -> bool {
                    #terminated
                }
            }
        }
    }

    fn handle_fn(&self) -> TokenStream {
        let context = &self.model.context;
        let arms = self.match_arms(&quote!(false), |_, state| Some(Self::handle_arm(state)));
        quote! {
            fn handle<E: ::core::any::Any>(&mut self, ctx: &mut #context, event: &E) -> bool {
                match self.state { #arms }
            }
        }
    }

    fn handle_arm(state: &State) -> TokenStream {
        let handler = handler_name(state);
        let own = quote! { self.#handler(ctx, event) };
        let Some(ty) = state.composite() else {
            return own;
        };
        let field = Model::sub_field(state);
        quote! {
            if <#ty as ::sml::StateMachine>::handle(&mut self.#field, ctx, event) {
                self.__sml_run_anonymous(ctx);
                true
            } else {
                #own
            }
        }
    }

    fn rows_from(&self, state: usize) -> impl Iterator<Item = &Transition> {
        self.model
            .transitions
            .iter()
            .filter(move |t| t.source == state)
    }

    /// Match arms over all states; states without an arm share one `=> default`.
    fn match_arms(
        &self,
        default: &TokenStream,
        mut arm: impl FnMut(usize, &State) -> Option<TokenStream>,
    ) -> TokenStream {
        let state_enum = &self.model.state_enum;
        let mut arms = Vec::new();
        let mut rest = Vec::new();
        for (index, state) in self.model.states.iter().enumerate() {
            let name = &state.name;
            match arm(index, state) {
                Some(body) => arms.push(quote! { #state_enum::#name => { #body } }),
                None => rest.push(quote! { #state_enum::#name }),
            }
        }
        if !rest.is_empty() {
            arms.push(quote! { #(#rest)|* => #default, });
        }
        quote! { #(#arms)* }
    }

    fn sub_machine_impls(&self) -> TokenStream {
        let name = &self.model.name;
        let impls = self.sub_fields().map(|(field, ty)| {
            quote! {
                impl ::sml::SubMachine<#ty> for #name {
                    fn sub(&self) -> &#ty {
                        &self.#field
                    }
                }
            }
        });
        quote! { #(#impls)* }
    }

    fn helpers(&self) -> TokenStream {
        let Model { name, .. } = self.model;
        let enter = self.enter_fn();
        let exit = self.exit_fn();
        let anonymous = self.anonymous_fn();
        let handlers = (self.model.states.iter().enumerate())
            .map(|(index, state)| self.state_handler(index, state));
        quote! {
            impl #name {
                #enter
                #exit
                #anonymous
                #(#handlers)*
            }
        }
    }

    fn enter_fn(&self) -> TokenStream {
        let context = &self.model.context;
        let arms = self.match_arms(&quote!({}), |_, state| {
            let actions = state_actions(&state.entry);
            let sub = state.composite().map(|ty| {
                let field = Model::sub_field(state);
                quote! { <#ty as ::sml::StateMachine>::enter(&mut self.#field, ctx); }
            });
            (!state.entry.is_empty() || sub.is_some()).then(|| quote! { #actions #sub })
        });
        quote! {
            fn __sml_enter_state(&mut self, ctx: &mut #context) {
                match self.state { #arms }
                self.__sml_run_anonymous(ctx);
            }
        }
    }

    fn exit_fn(&self) -> TokenStream {
        let context = &self.model.context;
        let arms = self.match_arms(&quote!({}), |_, state| {
            let actions = state_actions(&state.exit);
            let sub = state.composite().map(|ty| {
                let field = Model::sub_field(state);
                quote! { <#ty as ::sml::StateMachine>::exit(&mut self.#field, ctx); }
            });
            (!state.exit.is_empty() || sub.is_some()).then(|| quote! { #sub #actions })
        });
        quote! {
            fn __sml_exit_state(&mut self, ctx: &mut #context) {
                match self.state { #arms }
            }
        }
    }

    fn anonymous_fn(&self) -> TokenStream {
        let context = &self.model.context;
        let arms = self.match_arms(&quote!({}), |index, _| {
            let ev = quote!(&());
            let rows: Vec<TokenStream> = self
                .rows_from(index)
                .filter(|t| is_anonymous(&t.trigger))
                .map(|t| {
                    let guard = guard_condition(t.guard.as_ref(), &ev);
                    let fire = self.fire(t, &ev);
                    quote! { if #guard { #fire return; } }
                })
                .collect();
            (!rows.is_empty()).then(|| quote! { #(#rows)* })
        });
        quote! {
            fn __sml_run_anonymous(&mut self, ctx: &mut #context) {
                match self.state { #arms }
            }
        }
    }

    fn state_handler(&self, index: usize, state: &State) -> TokenStream {
        let context = &self.model.context;
        let handler = handler_name(state);
        let has_unexpected = self.rows_from(index).any(|t| is_unexpected(&t.trigger));
        let mark = has_unexpected.then(|| quote! { known = true; });
        let mut expected = Vec::new();
        let mut unexpected = Vec::new();
        for row in self.rows_from(index) {
            match &row.trigger {
                TransitionTrigger::Anonymous => {}
                TransitionTrigger::Event(ty) => {
                    expected.push(self.typed_row(ty, row, mark.as_ref()));
                }
                TransitionTrigger::Unexpected(Some(ty)) => {
                    unexpected.push(self.typed_row(ty, row, None));
                }
                TransitionTrigger::Unexpected(None) => unexpected.push(self.any_row(row)),
            }
        }
        let body = match (expected.is_empty(), unexpected.is_empty()) {
            (_, true) => quote! { #(#expected)* },
            (true, false) => quote! { #(#unexpected)* },
            (false, false) => quote! {
                let mut known = false;
                #(#expected)*
                if !known { #(#unexpected)* }
            },
        };
        quote! {
            fn #handler<E: ::core::any::Any>(&mut self, ctx: &mut #context, event: &E) -> bool {
                let event: &dyn ::core::any::Any = event;
                #body
                false
            }
        }
    }

    /// Row for event type `ty`; `mark` runs when the type matches, before the guard.
    fn typed_row(
        &self,
        ty: &syn::Type,
        row: &Transition,
        mark: Option<&TokenStream>,
    ) -> TokenStream {
        let ev = quote!(ev);
        let guard = guard_condition(row.guard.as_ref(), &ev);
        let fire = self.fire(row, &ev);
        quote! {
            if let Some(ev) = event.downcast_ref::<#ty>() {
                #mark
                if #guard { #fire return true; }
            }
        }
    }

    fn any_row(&self, row: &Transition) -> TokenStream {
        let ev = quote!(event);
        let guard = guard_condition(row.guard.as_ref(), &ev);
        let fire = self.fire(row, &ev);
        quote! { if #guard { #fire return true; } }
    }

    /// Statements performing `row` once its guard held; `ev` is the event.
    fn fire(&self, row: &Transition, ev: &TokenStream) -> TokenStream {
        let actions = row.actions.iter().map(|action| {
            quote_spanned! {action.span()=>
                ::sml::__private::log_action(::core::stringify!(#action));
                ::sml::__private::Action::call(&(#action), ctx, #ev);
            }
        });
        let Some(target) = row.target else {
            return quote! { #(#actions)* self.__sml_run_anonymous(ctx); };
        };
        let state_enum = &self.model.state_enum;
        let target = &self.model.states[target].name;
        quote! {
            ::sml::__private::log_state_change::<Self>(&self.state, &#state_enum::#target);
            self.__sml_exit_state(ctx);
            #(#actions)*
            self.state = #state_enum::#target;
            self.__sml_enter_state(ctx);
        }
    }
}

fn is_terminate(state: &State) -> bool {
    match state.kind {
        StateKind::Terminate => true,
        StateKind::Simple | StateKind::Composite(_) => false,
    }
}

fn handler_name(state: &State) -> Ident {
    format_ident!("__sml_handle_{}", to_snake_case(&state.name.to_string()))
}

fn state_actions(actions: &[Expr]) -> TokenStream {
    let calls = actions.iter().map(|action| {
        quote_spanned! {action.span()=>
            ::sml::__private::log_action(::core::stringify!(#action));
            ::sml::__private::Action::call(&(#action), ctx, &());
        }
    });
    quote! { #(#calls)* }
}

fn guard_condition(guard: Option<&GuardExpr>, ev: &TokenStream) -> TokenStream {
    let Some(guard) = guard else {
        return quote! { true };
    };
    match guard {
        GuardExpr::Leaf(expr) => {
            quote_spanned! {expr.span()=>
                ::sml::__private::log_guard(
                    ::core::stringify!(#expr),
                    ::sml::__private::Guard::check(&(#expr), &*ctx, #ev),
                )
            }
        }
        GuardExpr::Not(inner) => {
            let inner = guard_condition(Some(inner), ev);
            quote! { !(#inner) }
        }
        GuardExpr::And(left, right) => {
            let left = guard_condition(Some(left), ev);
            let right = guard_condition(Some(right), ev);
            quote! { (#left) && (#right) }
        }
        GuardExpr::Or(left, right) => {
            let left = guard_condition(Some(left), ev);
            let right = guard_condition(Some(right), ev);
            quote! { (#left) || (#right) }
        }
    }
}
